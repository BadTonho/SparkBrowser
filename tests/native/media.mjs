export async function checkMediaMute({invoke,until,fixture,click,restart,script,openSettings,closeSettings}) {
  if (!['win32','linux'].includes(process.platform)) return;
  const packet = await invoke('create_tab', {url: fixture.origin+'/page/media-a'});
  const a = packet.tabs.find(t=>t.is_active).id;
  await until(async()=> (await invoke('get_tab_media')).tabs.find(t=>t.tab_id===a)?.audible, 'native audio activity');
  const next = await invoke('create_tab', {url:fixture.origin+'/page/media-b'});
  const b = next.tabs.find(t=>t.is_active).id;
  await until(()=>script('return Boolean(document.querySelector(`[data-media-tab="${arguments[0]}"]`))', a),'background mute control');
  await click(`[data-media-tab="${a}"]`);
  await until(async()=> (await invoke('get_tab_media')).tabs.find(t=>t.tab_id===a)?.muted,'background tab muted');
  assert.equal((await invoke('get_tabs')).tabs.find(t=>t.is_active).id,b,'mute does not select/reorder the tab');
  await invoke('switch_tab',{tabId:a});
  await invoke('navigate_to',{input:fixture.origin+'/page/media-c'});
  await until(()=>fixture.reports.has('media-c'),'navigation');
  assert.equal((await invoke('get_tab_media')).tabs.find(t=>t.tab_id===a).muted,true);
  await invoke('set_tab_muted',{tabId:a,muted:false});
  await until(async()=> !(await invoke('get_tab_media')).tabs.find(t=>t.tab_id===a)?.muted,'unmuted');
  await invoke('set_tab_muted',{tabId:a,muted:true});
  await restart();
  await until(async()=> (await invoke('get_tab_media')).tabs.find(t=>t.tab_id===a)?.mute_available,'restored view');
  assert.equal((await invoke('get_tab_media')).tabs.find(t=>t.tab_id===a).muted,false,'mute is not persisted');
  await openSettings(); await click('[data-testid=settings-appearance_layout]');
  await until(()=>script('return Boolean(document.querySelector("#setting-browser-layout"))'),'layout settings');
  await click('#setting-browser-layout .mini-pill:nth-child(2)'); await closeSettings();
  await until(()=>script('return Boolean(document.querySelector(`.tab-row [data-media-tab="${arguments[0]}"]`))',a),'vertical mute control');
  await click(`[data-media-tab="${a}"]`);await until(async()=> (await invoke('get_tab_media')).tabs.find(t=>t.tab_id===a)?.muted,'vertical mute');
  fixture.commands.set('media-c','stop-media');await until(async()=> !(await invoke('get_tab_media')).tabs.find(t=>t.tab_id===a)?.audible,'audio stopped');
  fixture.commands.set('media-c','oscillator');await until(async()=> (await invoke('get_tab_media')).tabs.find(t=>t.tab_id===a)?.audible,'pure Web Audio observed while muted');
  assert.ok((await invoke('get_tabs')).tabs.find(t=>t.id===a).activity.playing_media,'Web Audio remains protected');
  await invoke('set_tab_muted',{tabId:a,muted:false});

}

export async function checkMediaVolume(context) {
  const {invoke,until,fixture,click,script,restart,withWebview}=context;
  if(process.platform!=='win32')return;
  const packet=await invoke('create_tab',{url:fixture.origin+'/page/media-volume'});
  const id=packet.tabs.find(t=>t.is_active).id;
  await until(()=>fixture.reports.has('media-volume'),'audio fixture');
  await until(async()=> (await invoke('get_tab_media')).tabs.find(t=>t.tab_id===id)?.audible,'audio ready before gain checks');
  const read=async()=> (await invoke('refresh_tab_media',{tabId:id})).tabs.find(t=>t.tab_id===id);
  let state=await until(async()=>{const s=await read();return s.document_key&&s.frames.some(f=>f.count)?s:null;},'media documents');
  const set=async volume=>{state=(await invoke('set_tab_volume',{tabId:id,volume,documentKey:state.document_key})).tabs.find(t=>t.tab_id===id);assert.equal(state.applied_volume,volume);};
  await set(50);await until(()=>fixture.reports.get('media-volume')?.nativeVolume===0.5,'native attenuation');
  assert.equal(fixture.reports.get('media-volume').playerVolume,1,'player volume stays independent');
  fixture.commands.set('media-volume','native-player-volume');
  await until(()=>fixture.reports.get('media-volume')?.nativeVolume===0.4&&fixture.reports.get('media-volume')?.playerVolume===0.8,'player control keeps the tab multiplier');
  fixture.commands.set('media-volume','restore-player-volume');await until(()=>fixture.reports.get('media-volume')?.nativeVolume===0.5,'player level restored');
  const originalRms=300/32768/Math.sqrt(2);
  await set(200);await until(()=>{const r=fixture.reports.get('media-volume');return r?.audioGain===2&&r.audioRms>originalRms*1.8&&r.audioRms<originalRms*2.2;},'stable doubled waveform');
  const doubled=fixture.reports.get('media-volume').audioRms;
  await set(150);await until(()=>{const r=fixture.reports.get('media-volume');return r?.audioGain===1.5&&r.audioRms/doubled>0.65&&r.audioRms/doubled<0.85;},'stable waveform at 150 percent');
  const ratio=fixture.reports.get('media-volume').audioRms/doubled;
  assert.ok(ratio>0.65&&ratio<0.85,`waveform gain ratio ${ratio}`);
  await set(0);assert.equal(state.muted,false,'zero volume is independent of mute');
  await invoke('set_tab_muted',{tabId:id,muted:true});await set(100);assert.equal(state.muted,true);await invoke('set_tab_muted',{tabId:id,muted:false});
  await checkVolumePopover(context, id);
  fixture.commands.set('media-volume','stop-media');
  await until(async()=> !(await invoke('get_tabs')).tabs.find(t=>t.id===id)?.activity.playing_media,'pause before hibernation');
  const other=(await invoke('create_tab',{url:fixture.origin+'/page/volume-other'})).tabs.find(t=>t.is_active).id;
  await invoke('hibernate_tab',{tabId:id});await invoke('switch_tab',{tabId:id});
  await until(()=>fixture.loads.get('media-volume')===2&&fixture.reports.get('media-volume')?.nativeVolume===0.8,'volume follows hibernated tab');
  state=await read();
  await invoke('set_split_view',{leftTabId:id,rightTabId:other});await invoke('switch_tab',{tabId:other});
  const splitReady=Date.now();
  for (const page of ['media-volume','volume-other']) await until(()=>fixture.reports.get(page)?.visibility==='visible' && fixture.reports.get(page)?.reportedAt>splitReady,'fresh split visibility');
  const visibility = [fixture.reports.get('media-volume').hiddenCount,fixture.reports.get('volume-other').hiddenCount];
  await click('[data-testid=open-media]');
  await until(()=>script('return document.querySelector("[data-testid=open-media]")?.getAttribute("aria-expanded")==="true"'),'popover follows focused pane');
  await withWebview('/media-popover.html',async()=>{
    await until(()=>script('return !document.querySelector("#media-popover").hidden && document.querySelector("input").disabled'),'unavailable focused pane keeps the volume slider disabled');
    await script('window.dispatchEvent(new KeyboardEvent("keydown",{key:"Escape",bubbles:true}));');
  });
  assert.equal((await invoke('get_tab_media')).tabs.find(t=>t.tab_id===other)?.volume,100);
  await until(()=>script('return document.querySelector("[data-testid=open-media]")?.getAttribute("aria-expanded")==="false"'),'popover closes');
  for (const page of ['media-volume','volume-other']) await until(()=>fixture.reports.get(page)?.visibility==='visible','split pane stays visible');
  assert.deepEqual([fixture.reports.get('media-volume').hiddenCount,fixture.reports.get('volume-other').hiddenCount],visibility,'popover preserves both split panes');
  await invoke('set_split_view',{leftTabId:null,rightTabId:null});await invoke('switch_tab',{tabId:id});
  const old=state.document_key;
  await invoke('navigate_to',{input:fixture.origin+'/page/media-next'});await until(()=>fixture.reports.has('media-next'),'next document');
  await assert.rejects(()=>invoke('set_tab_volume',{tabId:id,volume:150,documentKey:old}),/media.stale/);
  state=await read();await set(100);
  fixture.commands.set('media-next','cross-audio');await until(()=>fixture.reports.get('media-next')?.reportedAt>0,'cross source');
  await new Promise(r=>setTimeout(r,400));state=await read();
  const limited=(await invoke('set_tab_volume',{tabId:id,volume:200,documentKey:state.document_key})).tabs.find(t=>t.tab_id===id);
  assert.equal(limited.applied_volume,100);assert.equal(limited.volume_status,'limited');
  await until(()=>fixture.reports.get('media-next')?.nativeMuted===false,'unsupported audio preserved');
  fixture.commands.set('media-next','native-controls');await new Promise(r=>setTimeout(r,300));
  state=await read();const nativeControls=(await invoke('set_tab_volume',{tabId:id,volume:150,documentKey:state.document_key})).tabs.find(t=>t.tab_id===id);assert.equal(nativeControls.applied_volume,100);assert.equal(nativeControls.volume_status,'limited');
  await restart();const restored=(await invoke('get_tab_media')).tabs.find(t=>t.tab_id===id);assert.equal(restored.volume,100);
}

export async function checkMediaPip(context) {
  const {invoke,until,fixture,script,wait,click,screenshot,focusWindow}=context;
  if(process.platform!=='win32')return;
  await invoke('set_resident_limit',{limit:8});
  const initial=await invoke('create_tab',{url:fixture.origin+'/page/media-pip'});
  const id=initial.tabs.find(t=>t.is_active).id;
  await until(()=>fixture.reports.has('media-pip'),'pip document');
  await until(()=>script('return document.querySelector("[data-testid=toggle-pip]")?.disabled'),'PiP button is visible but disabled without videos');
  fixture.commands.set('media-pip','videos');
  await until(()=>fixture.reports.get('media-pip')?.videoCount===2,'two video candidates');
  const read=async()=> (await invoke('get_tab_media')).tabs.find(t=>t.tab_id===id);
  const state=await until(async()=> {const s=await read();return s.frames.flatMap(f=>f.videos).filter(v=>v.eligible).length===2?s:null;},'ready video candidates');
  const candidates=state.frames.flatMap(frame=>frame.videos.filter(video=>video.eligible).map(video=>({frame,video})));
  const largest=candidates.reduce((best,next)=>next.video.width*next.video.height>best.video.width*best.video.height?next:best);
  await until(()=>script('return document.querySelector("[data-testid=toggle-pip]")?.disabled===false'),'automatic PiP discovery without volume');
  assert.equal(await script('return document.querySelector("[data-testid=open-media]").getAttribute("aria-expanded");'),'false');
  assert.equal(await script('return document.querySelector("[data-testid=open-media]").nextElementSibling?.matches("[data-testid=toggle-pip]");'),true,'PiP sits immediately after volume');
  await screenshot('pip-toolbar');
  await click('[data-testid=toggle-pip]');
  await until(async()=> (await read()).frames.some(f=>f.picture_in_picture),'actual floating video');
  assert.ok((await read()).frames.some(f=>f.pip_mode==='custom'),'compatible source uses custom controls');
  await checkMinimalPlayer(context);
  await checkFloatingVolume(context,id);
  await withFloatingPlayer(context,()=>script('const s=document.querySelector("[data-testid=pip-volume]");s.value="37";s.dispatchEvent(new Event("input",{bubbles:true}));document.querySelector("[data-testid=pip-close]").click();'));
  await until(async()=>{const s=await read();return s.applied_volume===37&&!s.frames.some(f=>f.picture_in_picture);},'closing commits the final volume edit');
  assert.equal(await context.withWebview('/page/media-pip',()=>script('return [...document.querySelectorAll("video")].every(v=>!v.paused);')),true,'closing preserves original video playback');
  assert.equal(await context.withWebview('/page/media-pip',()=>script('return [...document.querySelectorAll("video")].every(v=>getComputedStyle(v).visibility!=="hidden");')),true,'closing restores the original image');
  await until(()=>script('return document.querySelector("[data-testid=toggle-pip]")?.disabled===false'),'close operation releases the toolbar');
  await click('[data-testid=toggle-pip]');
  await until(async()=> (await read()).frames.some(f=>f.pip_mode==='custom'),'rapid reopening creates a fresh session');
  await checkFloatingFrameChurn(context,id);
  await until(async()=> (await invoke('get_tabs')).tabs.find(t=>t.id===id)?.activity.picture_in_picture,'immediate pip protection');
  await until(async()=> (await read()).frames.some(frame=>frame.pip_video===largest.video.id),'toolbar selects the largest eligible video');
  await until(()=>script('return document.querySelector("[data-testid=toggle-pip]").getAttribute("aria-pressed")==="true"'),'toolbar indicates floating video');
  await invoke('set_overlay_visibility',{visible:true});
  await invoke('set_overlay_visibility',{visible:false});
  fixture.commands.set('media-pip','stop-media');
  await until(async()=> !(await invoke('get_tabs')).tabs.find(t=>t.id===id)?.activity.playing_media,'paused media');
  const next=await invoke('create_tab',{url:fixture.origin+'/page/pip-other'});const other=next.tabs.find(t=>t.is_active).id;
  await invoke('set_resident_limit',{limit:1});
  const details=(await invoke('get_diagnostics')).tab_details.find(t=>t.id===id);
  assert.equal(details.resident,true);assert.ok(details.protection_reasons.includes('picture_in_picture'));
  await assert.rejects(()=>invoke('hibernate_tab',{tabId:id}));
  const closed=await invoke('close_tabs_reviewed',{tabIds:[id]});assert.ok(closed.preserved.some(t=>t.id===id));
  assert.equal((await read()).frames.some(f=>f.picture_in_picture),true,'popup survives background and overlays');
  await invoke('create_workspace',{id:'media-pip-workspace',name:'Media test',icon:'T',accentPrimary:'#888888',accentSecondary:'#999999'});
  await invoke('move_tab_to_workspace',{tabId:other,workspaceId:'media-pip-workspace'});await invoke('switch_workspace',{workspaceId:'media-pip-workspace'});
  assert.equal((await read()).frames.some(f=>f.picture_in_picture),true,'popup survives workspace change');
  await checkBackgroundFloatingVolume(context,id,other);
  await until(()=>script('const b=document.querySelector("[data-testid=toggle-pip]");return !b.disabled && b.getAttribute("aria-pressed")==="true";'),'background floating video remains controllable');
  await click('[data-testid=toggle-pip]');
  await until(async()=> !(await read()).frames.some(f=>f.picture_in_picture),'toolbar exits PiP from another tab');
  await invoke('switch_tab',{tabId:id});await until(async()=> (await invoke('get_tabs')).tabs.find(t=>t.is_active)?.id===id,'return to origin tab');
  await invoke('set_resident_limit',{limit:8});
  const live=await read();const frame=live.frames.find(f=>f.videos.length===2);
  await invoke('enter_video_pip',{tabId:id,context:frame.context,document:frame.document,video:frame.videos[1].id});
  await until(async()=> (await invoke('get_tab_media')).tabs.find(t=>t.tab_id===id)?.frames.some(f=>f.pip_video===frame.videos[1].id),'second selected video');
  assert.equal((await invoke('get_tab_media')).tabs.flatMap(t=>t.frames).filter(f=>f.picture_in_picture).length,1,'one popup at a time');
  await click('[data-testid=toggle-pip]');await until(async()=> !(await read()).frames.some(f=>f.picture_in_picture),'exit native PiP through toolbar');
  await invoke('enter_video_pip',{tabId:id,context:frame.context,document:frame.document,video:frame.videos[1].id});
  await withFloatingPlayer(context,()=>script('window.close();'));await until(async()=> !(await invoke('get_tabs')).tabs.find(t=>t.id===id)?.activity.picture_in_picture,'external PiP close event');
  await until(()=>script('return document.querySelector("[data-testid=toggle-pip]").getAttribute("aria-pressed")==="false"'),'toolbar reflects external closure');
  await context.withWebview('/page/media-pip',()=>script('document.querySelectorAll("video").forEach(v=>{v.captureStream=()=>{throw new DOMException("Fixture capture blocked","SecurityError")};});'));
  await invoke('enter_video_pip',{tabId:id,context:frame.context,document:frame.document,video:frame.videos[0].id});
  await until(async()=> (await read()).frames.some(f=>f.pip_mode==='native'),'blocked capture retains native PiP');
  await until(()=>script('return document.querySelector(".media-notice")?.textContent.includes("nativa");'),'translated native fallback notice');
  await click('.media-notice button');
  await invoke('exit_video_pip');
  await context.withWebview('/page/media-pip',()=>script('document.querySelectorAll("video").forEach(v=>delete v.captureStream);'));
  await checkPipToolbarLayouts(context,id);
  await invoke('enter_video_pip',{tabId:id,context:frame.context,document:frame.document,video:frame.videos[0].id});
  await invoke('navigate_to',{input:fixture.origin+'/page/media-after-pip'});await until(()=>fixture.reports.has('media-after-pip'),'navigate closes popup');
  await until(async()=> !(await invoke('get_tabs')).tabs.find(t=>t.id===id)?.activity.picture_in_picture,'new document clears protection');
  await assert.rejects(()=>invoke('enter_video_pip',{tabId:id,context:frame.context,document:frame.document,video:frame.videos[0].id}),/media.stale/);
  fixture.commands.set('media-after-pip','media-frame');await until(()=>fixture.reports.has('media-frame'),'cross origin frame');
  fixture.commands.set('media-frame','videos');await until(()=>fixture.reports.get('media-frame')?.videoCount===2,'frame videos');
  // WebDriver DOM focus does not activate the OS window after native PiP closes.
  await focusWindow();
  await click('.omnibox-input');
  const framed=await until(async()=> {const s=await read();return s.frames.find(f=>f.videos.filter(v=>v.eligible).length===2);},'both native frame candidates ready');
  await until(()=>script('return !document.querySelector("[data-testid=toggle-pip]").disabled;'),'iframe enables toolbar button');
  await click('[data-testid=toggle-pip]');
  await until(async()=> (await read()).frames.some(f=>f.context===framed.context&&f.picture_in_picture&&f.pip_mode==='custom'),'cross origin custom PiP');
  await checkFloatingVolume(context,id);
  fixture.commands.set('media-frame','disable-pip');await wait(400);
  await assert.rejects(()=>invoke('enter_video_pip',{tabId:id,context:framed.context,document:framed.document,video:framed.videos[1].id}),/media.pip_unavailable/);
  await invoke('close_tab',{tabId:id});await until(()=>script('return !document.querySelector(`[data-tab-id="${arguments[0]}"]`)',id),'close origin tab');
  assert.ok(!(await invoke('get_tab_media')).tabs.some(t=>t.tab_id===id),'closed tab media state discarded');
  assert.ok((await invoke('get_tabs')).tabs.some(t=>t.id===other));
}
