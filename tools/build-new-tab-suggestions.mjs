// Turns the address bar's suggestion ranking into a script for the new tab page, so both lists stay the same.
// The new tab page is plain scripts without a build step, so the result is committed;
// `tests/new-tab-suggestions.test.mjs` fails when it is out of date. Run with `npm run build:suggestions`.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = new URL('../', import.meta.url);
export const OUTPUT = fileURLToPath(new URL('public/new-tab/suggestions-core.js', root));

export async function bundle() {
  const result = await build({
    entryPoints: [fileURLToPath(new URL('src/lib/services/address-suggestions.js', root))],
    bundle: true,
    write: false,
    format: 'iife',
    globalName: 'SparkSuggestions',
    target: 'es2020',
    legalComments: 'none',
    banner: { js: '// Generated by tools/build-new-tab-suggestions.mjs from src/lib/services/address-suggestions.js. Do not edit; run `npm run build:suggestions`.' },
  });
  return result.outputFiles[0].text.replace(/\r\n/g, '\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(OUTPUT, await bundle());
  console.log(`Wrote ${OUTPUT}`);
}
