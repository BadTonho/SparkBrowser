// Bundles the background editor's engine into the script the new tab page loads. The new tab page is plain
// scripts without a build step, so the result is committed; `tests/nebula-background.test.mjs` fails when it
// is out of date. Run with `npm run build:nebula`.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = new URL('../', import.meta.url);
export const OUTPUT = fileURLToPath(new URL('public/new-tab/nebula-background.js', root));

export async function bundle() {
  const result = await build({
    entryPoints: [fileURLToPath(new URL('src/lib/wallpaper/background-entry.ts', root))],
    bundle: true,
    write: false,
    format: 'iife',
    target: 'es2020',
    legalComments: 'none',
    banner: { js: '// Generated by tools/build-nebula-background.mjs from src/lib/wallpaper. Do not edit; run `npm run build:nebula`.' },
  });
  return result.outputFiles[0].text.replace(/\r\n/g, '\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(OUTPUT, await bundle());
  console.log(`Wrote ${OUTPUT}`);
}
